-- Caché de whitelist: operaciones, reemplazo, ETag y persistencia con
-- natives simuladas.

local function cleanState()
  BridgeWhitelist.reset()
  SimulatedNatives.files = {}
  SimulatedNatives.lastSave = nil
  BridgeApi.resetErrors()
end

test("whitelist: add/has/remove y validación de IDs", function()
  cleanState()
  assertFalse(BridgeWhitelist.has("570885174588854282"), "vacío al inicio")
  assertTrue(BridgeWhitelist.add("570885174588854282"), "add")
  assertTrue(BridgeWhitelist.has("570885174588854282"), "has")
  assertFalse(BridgeWhitelist.add("570885174588854282"), "ya estaba")
  assertFalse(BridgeWhitelist.add("abc"), "ID inválido")
  assertFalse(BridgeWhitelist.add("1234"), "demasiado corto")
  assertFalse(BridgeWhitelist.add(string.rep("9", 21)), "demasiado largo")
  assertFalse(BridgeWhitelist.remove("99999999999999999"), "no existía")
  assertTrue(BridgeWhitelist.remove("570885174588854282"), "remove")
  assertEq(BridgeWhitelist.count(), 0, "count")
end)

test("whitelist: replace limpia el estado anterior y filtra IDs", function()
  cleanState()
  BridgeWhitelist.add("999999999999999999")
  BridgeWhitelist.replace(42, true, { "570885174588854282", "basura" })
  assertEq(BridgeWhitelist.version(), 42, "version")
  assertTrue(BridgeWhitelist.isEnabled(), "enabled")
  assertEq(BridgeWhitelist.count(), 1, "solo el ID válido")
  assertFalse(BridgeWhitelist.has("999999999999999999"), "el viejo se fue")
  assertTrue(BridgeWhitelist.has("570885174588854282"), "el nuevo está")
  assertEq(BridgeWhitelist.etag(), '"wl-42"', "ETag con comillas")
end)

test("whitelist: setEnabled conmuta sin tocar el resto", function()
  cleanState()
  BridgeWhitelist.replace(1, false, { "570885174588854282" })
  assertFalse(BridgeWhitelist.isEnabled(), "off")
  BridgeWhitelist.setEnabled(true)
  assertTrue(BridgeWhitelist.isEnabled(), "on")
  assertEq(BridgeWhitelist.version(), 1, "version intacta")
  assertEq(BridgeWhitelist.count(), 1, "ids intactos")
end)

test("whitelist: serialize/deserialize ida y vuelta", function()
  cleanState()
  BridgeWhitelist.replace(7, true, { "570885174588854282", "12345678901234567890" })
  local text = BridgeWhitelist.serialize()
  BridgeWhitelist.reset()
  assertTrue(BridgeWhitelist.deserialize(text), "deserialize")
  assertEq(BridgeWhitelist.version(), 7, "version")
  assertTrue(BridgeWhitelist.isEnabled(), "enabled")
  assertEq(BridgeWhitelist.count(), 2, "count")
  assertTrue(BridgeWhitelist.has("12345678901234567890"), "id restaurado")
end)

test("whitelist: serialize ordena los IDs (formato estable)", function()
  cleanState()
  BridgeWhitelist.replace(1, false, { "999999999999999999", "111111111111111111" })
  assertContains(BridgeWhitelist.serialize(), '"111111111111111111","999999999999999999"', "orden")
end)

test("whitelist: deserialize rechaza JSON roto sin tocar el estado", function()
  cleanState()
  BridgeWhitelist.add("570885174588854282")
  assertFalse(BridgeWhitelist.deserialize("{{{"), "JSON roto")
  assertFalse(BridgeWhitelist.deserialize(nil), "nil")
  assertFalse(BridgeWhitelist.deserialize(""), "vacío")
  assertTrue(BridgeWhitelist.has("570885174588854282"), "la caché sigue intacta")
end)

test("whitelist: save/load con natives simuladas", function()
  cleanState()
  BridgeWhitelist.replace(9, true, { "570885174588854282" })
  BridgeWhitelist.save()
  assertEq(SimulatedNatives.lastSave.fileName, "cache/whitelist.json", "ruta")
  assertEq(SimulatedNatives.lastSave.resourceName, "lobbynest-bridge", "recurso")
  assertEq(SimulatedNatives.lastSave.dataLength, -1, "longitud automática")

  BridgeWhitelist.reset()
  assertFalse(BridgeWhitelist.has("570885174588854282"), "en memoria se limpió")
  assertTrue(BridgeWhitelist.load(), "load")
  assertEq(BridgeWhitelist.version(), 9, "version")
  assertTrue(BridgeWhitelist.has("570885174588854282"), "restaurado desde archivo")

  SimulatedNatives.files = {}
  BridgeWhitelist.reset()
  assertFalse(BridgeWhitelist.load(), "sin archivo no hay nada que cargar")
  assertEq(BridgeWhitelist.count(), 0, "count vacío")
end)
